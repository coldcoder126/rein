package session

import (
	"context"
	"errors"
	"time"
)

// ErrNotFound means the session does not exist.
var ErrNotFound = errors.New("session: not found")

// Session holds session metadata.
type Session struct {
	ID string
	// ParentID is the parent session that spawned this one. Each sub-agent task is stored in a session of its own;
	// it is not a conversation the user created, and listings of the user's sessions should usually exclude it.
	ParentID  string
	CreatedAt time.Time
}

// Store is the session store interface, which can be backed by a database and so on. Its methods are called concurrently for many sessions.
type Store interface {
	// EnsureSession creates the session if it does not exist and does nothing otherwise.
	EnsureSession(ctx context.Context, session Session) error
	GetSession(ctx context.Context, sessionID string) (Session, error)
	// AppendMessages appends messages in order. Message IDs are generated by the caller.
	// The runner calls it with a ctx that has no cancellation or deadline (messages already produced must still be written
	// after a run is canceled); an implementation that needs to bound write time should set its own timeout.
	AppendMessages(ctx context.Context, sessionID string, messages ...Message) error
	// ListMessages returns all messages of the session in append order.
	ListMessages(ctx context.Context, sessionID string) ([]Message, error)
}

// DisplayMessages returns the messages to show to the user (those with Visible set).
func DisplayMessages(messages []Message) []Message {
	out := make([]Message, 0, len(messages))
	for _, msg := range messages {
		if msg.Visible {
			out = append(out, msg)
		}
	}
	return out
}
