package session

import (
	"context"
	"errors"
	"time"
)

var (
	// ErrNotFound means the session, or a message it should hold, does not exist.
	ErrNotFound = errors.New("session: not found")
	// ErrExists means a session that must be new already exists.
	ErrExists = errors.New("session: already exists")
)

// Session holds session metadata.
type Session struct {
	ID string
	// ParentID is the parent session that spawned this one. Each sub-agent task is stored in a session of its own;
	// it is not a conversation the user created, and listings of the user's sessions should usually exclude it.
	ParentID string
	// ForkOf and ForkAt are set on a session made by Fork: the session it was forked from, and the user message that was
	// left out there, to be replaced by new input; ForkAt is empty when the whole session was copied.
	ForkOf    string
	ForkAt    string
	CreatedAt time.Time
}

// Store is the session store interface, which can be backed by a database and so on. Its methods are called concurrently for many sessions.
// It does not gain methods: further capabilities are optional interfaces such as TailLister. The storetest package checks an implementation.
type Store interface {
	// EnsureSession creates the session if it does not exist and does nothing otherwise.
	EnsureSession(ctx context.Context, session Session) error
	GetSession(ctx context.Context, sessionID string) (Session, error)
	// AppendMessages appends messages in order. Message IDs are generated by the caller and unique within a session; the
	// same ID can appear in other sessions, as Fork copies messages with their IDs.
	// The runner calls it with a ctx that has no cancellation or deadline (messages already produced must still be written
	// after a run is canceled); an implementation that needs to bound write time should set its own timeout.
	// A batch need not be atomic: an interrupted write may keep its first messages only, which replay tolerates.
	AppendMessages(ctx context.Context, sessionID string, messages ...Message) error
	// ListMessages returns all messages the store keeps for the session, in append order, including those compaction
	// replaced. The framework never deletes messages; whether old ones are purged is up to the application, and tools that
	// read history (such as history.Tool) then only find what is kept.
	ListMessages(ctx context.Context, sessionID string) ([]Message, error)
}

// TailLister is an optional interface for stores that can read a session without the part compaction has replaced.
// The runner uses it when the store implements it and falls back to ListMessages otherwise, so it only saves reading:
// a long session is then loaded from its latest summary instead of from its first message.
//
// A store wrapped by another type (for logging, metrics and so on) only keeps it when the wrapper forwards it.
type TailLister interface {
	// ListTail returns what Tail returns for the session's messages, in append order.
	ListTail(ctx context.Context, sessionID string) ([]Message, error)
}

// Forker is an optional interface for stores that can fork a session, which Fork requires.
//
// A store wrapped by another type (for logging, metrics and so on) only keeps it when the wrapper forwards it.
type Forker interface {
	// ForkSession creates the session dst holding the messages of the session srcID that precede the message cutID, or all
	// of them when cutID is empty, in order, with their IDs and every field but SessionID, which becomes dst.ID.
	// It returns ErrExists when dst already exists and ErrNotFound when srcID or cutID does not. It is atomic: when it fails,
	// dst does not exist.
	ForkSession(ctx context.Context, dst Session, srcID, cutID string) error
}

// Tail returns the messages still used after the latest compaction: from the first message the latest summary keeps
// (Compaction.FirstKeptID) to the end, or from that summary when the kept message is not found. Without a summary it returns all.
func Tail(all []Message) []Message {
	return all[tailStart(all):]
}

// Compacted returns the messages the latest compaction replaced, the part of all that Tail leaves out, without the earlier
// summaries among them: their content is the messages themselves.
func Compacted(all []Message) []Message {
	var out []Message
	for _, msg := range all[:tailStart(all)] {
		if msg.Type != TypeSummary {
			out = append(out, msg)
		}
	}
	return out
}

// tailStart returns the index where Tail begins.
func tailStart(all []Message) int {
	last := -1
	for i, msg := range all {
		if msg.Type == TypeSummary {
			last = i
		}
	}
	if last < 0 {
		return 0
	}
	if c := all[last].Compaction; c != nil {
		for i, msg := range all[:last] {
			if msg.ID == c.FirstKeptID {
				return i
			}
		}
	}
	return last
}

// DisplayMessages returns the messages to show to the user (those with Visible set).
func DisplayMessages(messages []Message) []Message {
	out := make([]Message, 0, len(messages))
	for _, msg := range messages {
		if msg.Visible {
			out = append(out, msg)
		}
	}
	return out
}
