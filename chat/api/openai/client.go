// Package openai implements chat.Client with the OpenAI Responses API; it also works with endpoints compatible with the Responses API (such as DeepSeek).
package openai

import (
	"cmp"
	"context"
	"errors"
	"fmt"
	"iter"
	"net/http"
	"strings"
	"time"

	goopenai "github.com/openai/openai-go/v3"
	"github.com/openai/openai-go/v3/option"

	"github.com/coldcoder126/rein/chat"
)

const (
	providerName = "openai"

	// API is the protocol this client speaks, see chat.ModelInfo.API.
	API = "openai-responses"

	ModelGPT6Luna = "gpt-6-luna"

	defaultMaxInputTokens  = 128_000
	defaultMaxOutputTokens = 16_384
)

// APIKeyProvider resolves the API key dynamically, for short-lived tokens.
type APIKeyProvider func(ctx context.Context) (string, error)

// Config configures the Responses API Client.
type Config struct {
	// Endpoint is the service the client talks to: the zero value is OpenAI's own, DeepSeek is a preset,
	// and any other compatible endpoint is described by filling one in.
	Endpoint       Endpoint
	APIKey         string
	APIKeyProvider APIKeyProvider
	Model          string
	// MaxInputTokens / MaxOutputTokens of 0 use the endpoint's limits, or 128000 / 16384 when it has none.
	MaxInputTokens  int
	MaxOutputTokens int
	Timeout         time.Duration
	MaxRetries      int
	Headers         map[string]string
	HTTPClient      *http.Client

	// Reasoning means the model is a reasoning model: requests ask for reasoning.summary and for encrypted reasoning content,
	// so history can be replayed statelessly. Regular models reject these parameters, so it is off by default.
	Reasoning bool
	// ImageGeneration enables the built-in image_generation tool so the model can generate images in its replies.
	// Images in assistant messages in history (including those generated by other models) are replayed as input_image in a user message regardless of this setting.
	ImageGeneration bool
	// FileScope names the Files API store this key reads, see chat.FileRef.Scope. It defaults to "openai" for the
	// official endpoint and to none for a custom BaseURL; set it per project when keys of several projects are in use.
	FileScope string
	// HTTPHooks are debugging hooks at the raw HTTP layer.
	HTTPHooks chat.HTTPHooks
}

// Client wraps the Responses API of the OpenAI SDK.
type Client struct {
	cfg Config
}

// New creates a Responses API chat.Client. It panics when cfg.Model is empty.
func New(cfg Config) *Client {
	if cfg.Model == "" {
		panic("openai: Config.Model must not be empty")
	}
	if cfg.Endpoint.Provider == "" {
		cfg.Endpoint.Provider = providerName
	}
	cfg.MaxInputTokens = cmp.Or(cfg.MaxInputTokens, cfg.Endpoint.MaxInputTokens, defaultMaxInputTokens)
	cfg.MaxOutputTokens = cmp.Or(cfg.MaxOutputTokens, cfg.Endpoint.MaxOutputTokens, defaultMaxOutputTokens)
	return &Client{cfg: cfg}
}

// Stream sends a streaming request.
func (c *Client) Stream(ctx context.Context, req chat.Request) iter.Seq[chat.Event] {
	return func(yield func(chat.Event) bool) {
		b := chat.NewBuilder(yield, c.modelInfo(req))

		client, err := c.newSDKClient(ctx)
		if err != nil {
			b.Fail(c.wrapError(ctx, err))
			return
		}
		params, err := c.buildParams(req)
		if err != nil {
			b.Fail(&chat.Error{Kind: chat.KindInvalidRequest, Err: err})
			return
		}
		stream := client.Responses.NewStreaming(ctx, params)
		defer stream.Close()

		state := newStreamState(b, c.cfg.Endpoint.Provider)
		for stream.Next() {
			if !state.handle(stream.Current()) {
				return
			}
		}
		if err := stream.Err(); err != nil {
			b.Fail(c.wrapError(ctx, fmt.Errorf("openai stream: %w", err)))
			return
		}
		state.finish()
	}
}

// Info returns the model info.
func (c *Client) Info() chat.ModelInfo {
	return chat.ModelInfo{
		Provider:         c.cfg.Endpoint.Provider,
		API:              API,
		Model:            c.cfg.Model,
		MaxInputTokens:   c.cfg.MaxInputTokens,
		MaxOutputTokens:  c.cfg.MaxOutputTokens,
		SupportsMedia:    !c.cfg.Endpoint.Compat.NoMedia,
		ImageOutput:      !c.cfg.Endpoint.Compat.NoMedia,
		StructuredOutput: !c.cfg.Endpoint.Compat.NoStructuredOutput,
		FileScope:        c.fileScope(),
		ImageLimits:      chat.DefaultImageLimits,
	}
}

// modelInfo returns the info of the model actually used by this request, for deciding on replay whether it is the same model.
func (c *Client) modelInfo(req chat.Request) chat.ModelInfo {
	info := c.Info()
	info.Model = c.resolveModel(req)
	return info
}

func (c *Client) resolveModel(req chat.Request) string {
	if req.Options.Model != "" {
		return req.Options.Model
	}
	return c.cfg.Model
}

func (c *Client) newSDKClient(ctx context.Context) (goopenai.Client, error) {
	opts := make([]option.RequestOption, 0, 6+len(c.cfg.Headers))
	apiKey := c.cfg.APIKey
	if c.cfg.APIKeyProvider != nil {
		key, err := c.cfg.APIKeyProvider(ctx)
		if err != nil {
			return goopenai.Client{}, fmt.Errorf("openai: resolve API key: %w", err)
		}
		apiKey = key
	}
	opts = append(opts, option.WithAPIKey(apiKey))
	if c.cfg.Endpoint.BaseURL != "" {
		opts = append(opts, option.WithBaseURL(c.cfg.Endpoint.BaseURL))
	}
	if hc := c.cfg.HTTPHooks.HTTPClient(c.cfg.HTTPClient); hc != nil {
		opts = append(opts, option.WithHTTPClient(hc))
	}
	if c.cfg.Timeout > 0 {
		opts = append(opts, option.WithRequestTimeout(c.cfg.Timeout))
	}
	if c.cfg.MaxRetries > 0 {
		opts = append(opts, option.WithMaxRetries(c.cfg.MaxRetries))
	}
	for k, v := range c.cfg.Headers {
		opts = append(opts, option.WithHeader(k, v))
	}
	return goopenai.NewClient(opts...), nil
}

func (c *Client) wrapError(ctx context.Context, err error) *chat.Error {
	var status int
	var retryAfter time.Duration
	var apiErr *goopenai.Error
	if errors.As(err, &apiErr) {
		status = apiErr.StatusCode
		if apiErr.Response != nil {
			retryAfter = chat.ParseRetryAfter(apiErr.Response.Header)
		}
		// The SDK's error message omits the response body, so add the error code and message from the server for classification and debugging.
		if detail := strings.TrimSpace(apiErr.Code + ": " + apiErr.Message); detail != ":" {
			err = fmt.Errorf("%s: %w", detail, err)
		}
	}
	ce := chat.WrapError(ctx, err, status, retryAfter)
	if ce.Message == "" {
		ce.Message = c.cfg.Endpoint.Provider
	}
	return ce
}
