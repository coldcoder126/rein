package chat

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"

	invopop "github.com/invopop/jsonschema"
	"github.com/santhosh-tekuri/jsonschema/v6"
)

// OutputFormat requires the model to produce output that follows a JSON Schema.
//
// When the model supports structured output natively (ModelInfo.StructuredOutput), the provider uses native constrained decoding;
// otherwise it writes the schema into the system prompt. Either way the result should be validated locally with ParseOutput.
// Providers accept different subsets of JSON Schema and OpenAI is the strictest: every object field is required and extra fields are forbidden.
// Schemas generated by SchemaFor meet this requirement.
type OutputFormat struct {
	// Name is the schema name, made of letters, digits, underscores and hyphens; it defaults to "output" when empty.
	Name string
	// Schema is the JSON Schema the output must satisfy; its root should be an object.
	Schema json.RawMessage
}

// SchemaOption adjusts how SchemaFor generates a schema.
type SchemaOption func(*schemaConfig)

type schemaConfig struct {
	allowOptional bool
}

// AllowOptional keeps optional fields: fields with omitempty are left out of required.
// Tool parameters use this form; structured output needs the default strict form.
func AllowOptional() SchemaOption {
	return func(c *schemaConfig) { c.allowOptional = true }
}

// SchemaFor generates a JSON Schema from a Go type, for structured output and tool parameters.
//
// By default every struct field is required and extra fields are forbidden, which satisfies the strict modes of all providers;
// field descriptions are given with the `jsonschema:"description=..."` tag.
func SchemaFor[T any](opts ...SchemaOption) (json.RawMessage, error) {
	var cfg schemaConfig
	for _, opt := range opts {
		opt(&cfg)
	}
	reflector := &invopop.Reflector{DoNotReference: true, Anonymous: true}
	schema := reflector.ReflectFromType(reflect.TypeFor[T]())
	raw, err := json.Marshal(schema)
	if err != nil {
		return nil, fmt.Errorf("chat: generate schema: %w", err)
	}
	var node map[string]any
	if err := json.Unmarshal(raw, &node); err != nil {
		return nil, fmt.Errorf("chat: generate schema: %w", err)
	}
	delete(node, "$schema")
	delete(node, "$id")
	if !cfg.allowOptional {
		strictObjects(node)
	}
	return json.Marshal(node)
}

// strictObjects recursively makes every object with properties require all fields and forbid extra ones.
func strictObjects(node any) {
	switch v := node.(type) {
	case map[string]any:
		if props, ok := v["properties"].(map[string]any); ok {
			required := make([]string, 0, len(props))
			for name := range props {
				required = append(required, name)
			}
			// Keep a stable order so that the same type always yields the same schema and does not break the prompt cache.
			sort.Strings(required)
			v["required"] = required
			v["additionalProperties"] = false
		}
		for _, child := range v {
			strictObjects(child)
		}
	case []any:
		for _, child := range v {
			strictObjects(child)
		}
	}
}

// WithOutputInstructions returns the request with the output format written into the system prompt and Output cleared,
// for providers without native structured output.
func WithOutputInstructions(req Request) Request {
	if req.Output == nil {
		return req
	}
	instructions := "Respond with a single JSON value and nothing else: no explanations and no markdown code fences."
	if len(req.Output.Schema) > 0 {
		instructions += " The JSON must conform to this JSON Schema:\n\n" + string(req.Output.Schema)
	}
	if strings.TrimSpace(req.SystemPrompt) == "" {
		req.SystemPrompt = instructions
	} else {
		req.SystemPrompt += "\n\n" + instructions
	}
	req.Output = nil
	return req
}

// ParseOutput extracts JSON from an assistant message and validates it against the schema of format.
// JSON wrapped in a markdown code block is unwrapped first. A failed validation returns an *Error of KindInvalidOutput.
func ParseOutput(msg *Message, format *OutputFormat) (json.RawMessage, error) {
	if msg == nil {
		return nil, &Error{Kind: KindInvalidOutput, Message: "no message to parse"}
	}
	if msg.StopReason == StopReasonLength {
		return nil, &Error{Kind: KindInvalidOutput, Message: "output was truncated, JSON is incomplete"}
	}
	text := stripCodeFence(msg.TextContent())
	if text == "" {
		return nil, &Error{Kind: KindInvalidOutput, Message: "model produced no text"}
	}
	value, err := jsonschema.UnmarshalJSON(strings.NewReader(text))
	if err != nil {
		return nil, &Error{Kind: KindInvalidOutput, Message: "output is not valid JSON", Err: err}
	}
	if format != nil && len(format.Schema) > 0 {
		schema, err := compileSchema(format.Schema)
		if err != nil {
			return nil, &Error{Kind: KindInvalidRequest, Message: "invalid output schema", Err: err}
		}
		if err := schema.Validate(value); err != nil {
			return nil, &Error{Kind: KindInvalidOutput, Message: "output does not match the schema", Err: err}
		}
	}
	return json.RawMessage(text), nil
}

// ValidateJSON validates a JSON document against a JSON Schema. An invalid schema also returns an error.
func ValidateJSON(schema, data json.RawMessage) error {
	compiled, err := compileSchema(schema)
	if err != nil {
		return fmt.Errorf("invalid schema: %w", err)
	}
	value, err := jsonschema.UnmarshalJSON(bytes.NewReader(data))
	if err != nil {
		return err
	}
	return compiled.Validate(value)
}

func compileSchema(raw json.RawMessage) (*jsonschema.Schema, error) {
	doc, err := jsonschema.UnmarshalJSON(bytes.NewReader(raw))
	if err != nil {
		return nil, err
	}
	compiler := jsonschema.NewCompiler()
	if err := compiler.AddResource("schema.json", doc); err != nil {
		return nil, err
	}
	return compiler.Compile("schema.json")
}

// stripCodeFence removes the markdown code fence around JSON.
func stripCodeFence(text string) string {
	text = strings.TrimSpace(text)
	if !strings.HasPrefix(text, "```") {
		return text
	}
	text = strings.TrimPrefix(text, "```")
	if i := strings.IndexByte(text, '\n'); i >= 0 {
		text = text[i+1:]
	}
	return strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(text), "```"))
}

// CompleteJSON requests structured output and decodes it into T.
//
// When req.Output is nil the schema is generated from T (T should be a struct). The returned message is the complete assistant
// message and can be appended to history. A failed model call, truncated output or output not matching the schema returns a typed *Error.
func CompleteJSON[T any](ctx context.Context, c Client, req Request) (T, *Message, error) {
	var out T
	if req.Output == nil {
		schema, err := SchemaFor[T]()
		if err != nil {
			return out, nil, &Error{Kind: KindInvalidRequest, Err: err}
		}
		req.Output = &OutputFormat{Schema: schema}
	}
	msg, err := Complete(ctx, c, req)
	if err != nil {
		return out, msg, err
	}
	raw, err := ParseOutput(msg, req.Output)
	if err != nil {
		return out, msg, err
	}
	if err := json.Unmarshal(raw, &out); err != nil {
		return out, msg, &Error{Kind: KindInvalidOutput, Message: "output cannot be decoded into the target type", Err: err}
	}
	return out, msg, nil
}
