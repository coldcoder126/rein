package openai

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/openai/openai-go/v3/packages/param"
	"github.com/openai/openai-go/v3/responses"
	"github.com/openai/openai-go/v3/shared"

	"github.com/coldcoder126/rein/chat"
)

const (
	// openaiMinOutputTokens is the lowest max_output_tokens the Responses API accepts.
	openaiMinOutputTokens = 16
	generatedImageNote    = "(Image generated by the assistant in the previous turn)"
)

func (c *Client) buildParams(req chat.Request) (responses.ResponseNewParams, error) {
	if c.cfg.NoStructuredOutput {
		req = chat.WithOutputInstructions(req)
	}
	input, err := convertMessages(chat.NormalizeForModel(req.Messages, c.modelInfo(req)))
	if err != nil {
		return responses.ResponseNewParams{}, err
	}
	params := responses.ResponseNewParams{
		Model: shared.ResponsesModel(c.resolveModel(req)),
		Input: responses.ResponseNewParamsInputUnion{OfInputItemList: input},
	}
	if strings.TrimSpace(req.SystemPrompt) != "" {
		params.Instructions = param.NewOpt(req.SystemPrompt)
	}

	maxTokens := req.MaxTokens
	if maxTokens <= 0 {
		maxTokens = c.cfg.MaxOutputTokens
	}
	if maxTokens > 0 {
		params.MaxOutputTokens = param.NewOpt(int64(max(maxTokens, openaiMinOutputTokens)))
	}
	if req.Temperature != nil {
		params.Temperature = param.NewOpt(*req.Temperature)
	}

	extra := map[string]any{}
	if req.Output != nil {
		var schema any
		if err := json.Unmarshal(req.Output.Schema, &schema); err != nil {
			return responses.ResponseNewParams{}, fmt.Errorf("openai: invalid output schema: %w", err)
		}
		name := req.Output.Name
		if name == "" {
			name = "output"
		}
		extra["text"] = map[string]any{"format": map[string]any{
			"type": "json_schema", "name": name, "schema": schema, "strict": true,
		}}
	}
	if !c.cfg.DisableStoreParams {
		params.Store = param.NewOpt(false)
		if c.cfg.Reasoning {
			extra["include"] = []string{"reasoning.encrypted_content"}
		}
	}
	if c.cfg.Reasoning {
		reasoning := map[string]any{"summary": "auto"}
		switch req.Reasoning {
		case "":
		case chat.ReasoningOff:
			reasoning["effort"] = "none"
		default:
			reasoning["effort"] = string(req.Reasoning)
		}
		extra["reasoning"] = reasoning
	}
	if len(req.Tools) > 0 {
		switch req.ToolChoice.Mode {
		case "":
		case chat.ToolChoiceAuto, chat.ToolChoiceNone, chat.ToolChoiceRequired:
			extra["tool_choice"] = string(req.ToolChoice.Mode)
		case chat.ToolChoiceTool:
			extra["tool_choice"] = map[string]any{"type": "function", "name": req.ToolChoice.Name}
		default:
			return responses.ResponseNewParams{}, fmt.Errorf("openai: unknown ToolChoice %q", req.ToolChoice.Mode)
		}
	}
	if len(extra) > 0 {
		params.SetExtraFields(extra)
	}

	tools, err := convertTools(req.Tools, c.cfg.ImageGeneration)
	if err != nil {
		return responses.ResponseNewParams{}, err
	}
	params.Tools = tools
	return params, nil
}

func rawItem(v map[string]any) responses.ResponseInputItemUnionParam {
	return param.Override[responses.ResponseInputItemUnionParam](v)
}

func convertMessages(messages []chat.Message) (responses.ResponseInputParam, error) {
	var items responses.ResponseInputParam
	var generated []map[string]any
	// Generated images in assistant messages cannot be replayed as assistant content (statelessly, image_generation_call refers to a
	// server-side item by id and returns 404), so they come back as input_image in a user message after that turn's tool results.
	flush := func() {
		if len(generated) == 0 {
			return
		}
		content := append([]map[string]any{{"type": "input_text", "text": generatedImageNote}}, generated...)
		items = append(items, rawItem(map[string]any{"type": "message", "role": "user", "content": content}))
		generated = nil
	}
	for i, m := range messages {
		switch m.Role {
		case chat.RoleUser:
			flush()
			content, err := userContent(m.Content)
			if err != nil {
				return nil, err
			}
			if len(content) > 0 {
				items = append(items, rawItem(map[string]any{"type": "message", "role": "user", "content": content}))
			}
		case chat.RoleAssistant:
			flush()
			assistant, images := assistantItems(i, m)
			items = append(items, assistant...)
			generated = images
		case chat.RoleTool:
			output, err := toolOutput(m.Content)
			if err != nil {
				return nil, err
			}
			items = append(items, rawItem(map[string]any{
				"type": "function_call_output", "call_id": m.ToolCallID, "output": output,
			}))
		default:
			return nil, fmt.Errorf("openai: unknown message role %q", m.Role)
		}
	}
	flush()
	return items, nil
}

func userContent(blocks []chat.ContentBlock) ([]map[string]any, error) {
	var content []map[string]any
	for _, block := range blocks {
		switch block.Type {
		case chat.ContentTypeText:
			if block.Text != "" {
				content = append(content, map[string]any{"type": "input_text", "text": block.Text})
			}
		case chat.ContentTypeMedia:
			content = append(content, mediaPart(block))
		default:
			return nil, fmt.Errorf("openai: user messages do not support content block type %q", block.Type)
		}
	}
	return content, nil
}

// mediaPart converts a media block into Responses input content: input_image for images and input_file for everything else, both inline or by URL.
func mediaPart(block chat.ContentBlock) map[string]any {
	inline := len(block.Data) > 0
	source := block.URL
	if inline {
		source = "data:" + block.MIMEType + ";base64," + base64.StdEncoding.EncodeToString(block.Data)
	}
	if block.IsImage() {
		return map[string]any{"type": "input_image", "detail": "auto", "image_url": source}
	}
	if !inline {
		return map[string]any{"type": "input_file", "file_url": source}
	}
	name := block.Name
	if name == "" {
		name = "file"
	}
	return map[string]any{"type": "input_file", "filename": name, "file_data": source}
}

// toolOutput converts a tool result into the output of function_call_output: a string for plain text, a content array when there is media.
func toolOutput(blocks []chat.ContentBlock) (any, error) {
	var text []string
	var media []map[string]any
	for _, block := range blocks {
		switch block.Type {
		case chat.ContentTypeText:
			if block.Text != "" {
				text = append(text, block.Text)
			}
		case chat.ContentTypeMedia:
			media = append(media, mediaPart(block))
		default:
			return nil, fmt.Errorf("openai: tool results do not support content block type %q", block.Type)
		}
	}
	joined := strings.Join(text, "\n")
	if len(media) == 0 {
		if joined == "" {
			return "(no tool output)", nil
		}
		return joined, nil
	}
	var parts []map[string]any
	if joined != "" {
		parts = append(parts, map[string]any{"type": "input_text", "text": joined})
	}
	return append(parts, media...), nil
}

// assistantItems rebuilds Responses input items from an assistant message in block order, and returns generated images that must be replayed separately.
// Stateless replay relies on block signatures: thinking blocks keep the full reasoning item, text blocks keep the message id and phase,
// and tool call blocks keep the item id of the function_call.
func assistantItems(msgIndex int, m chat.Message) ([]responses.ResponseInputItemUnionParam, []map[string]any) {
	var items []responses.ResponseInputItemUnionParam
	var images []map[string]any
	for blockIndex, block := range m.Content {
		switch block.Type {
		case chat.ContentTypeThinking:
			if block.Signature != "" && !block.Redacted {
				items = append(items, param.Override[responses.ResponseInputItemUnionParam](json.RawMessage(block.Signature)))
			}
		case chat.ContentTypeText:
			if block.Text == "" {
				continue
			}
			sig := decodeTextSignature(block.Signature)
			id := sig.ID
			if id == "" || len(id) > 64 {
				id = fmt.Sprintf("msg_ae_%d_%d", msgIndex, blockIndex)
			}
			item := map[string]any{
				"type": "message", "role": "assistant", "status": "completed", "id": id,
				"content": []map[string]any{{"type": "output_text", "text": block.Text, "annotations": []any{}}},
			}
			if sig.Phase != "" {
				item["phase"] = sig.Phase
			}
			items = append(items, rawItem(item))
		case chat.ContentTypeToolCall:
			if block.ToolCall == nil {
				continue
			}
			args := string(block.ToolCall.Arguments)
			if args == "" {
				args = "{}"
			}
			item := map[string]any{
				"type": "function_call", "call_id": block.ToolCall.ID, "name": block.ToolCall.Name, "arguments": args,
			}
			if block.Signature != "" {
				item["id"] = block.Signature
			}
			items = append(items, rawItem(item))
		case chat.ContentTypeMedia:
			images = append(images, mediaPart(block))
		}
	}
	return items, images
}

func convertTools(defs []chat.ToolDef, imageGeneration bool) ([]responses.ToolUnionParam, error) {
	var out []responses.ToolUnionParam
	for _, def := range defs {
		var schema map[string]any
		if len(def.InputSchema) > 0 {
			if err := json.Unmarshal(def.InputSchema, &schema); err != nil {
				return nil, fmt.Errorf("tool %q: invalid input_schema: %w", def.Name, err)
			}
		}
		if schema == nil {
			schema = map[string]any{"type": "object", "properties": map[string]any{}}
		}
		tool := map[string]any{"type": "function", "name": def.Name, "parameters": schema, "strict": false}
		if def.Description != "" {
			tool["description"] = def.Description
		}
		out = append(out, param.Override[responses.ToolUnionParam](tool))
	}
	if imageGeneration {
		out = append(out, param.Override[responses.ToolUnionParam](map[string]any{"type": "image_generation"}))
	}
	return out, nil
}

// textSignature is the content of a text block signature: the Responses message id and phase.
type textSignature struct {
	V     int    `json:"v"`
	ID    string `json:"id"`
	Phase string `json:"phase,omitempty"`
}

func encodeTextSignature(id, phase string) string {
	if id == "" {
		return ""
	}
	raw, _ := json.Marshal(textSignature{V: 1, ID: id, Phase: phase})
	return string(raw)
}

func decodeTextSignature(sig string) textSignature {
	var out textSignature
	if sig == "" || json.Unmarshal([]byte(sig), &out) != nil || out.V != 1 {
		return textSignature{}
	}
	if out.Phase != "commentary" && out.Phase != "final_answer" {
		out.Phase = ""
	}
	return out
}
