func TestBuildParamsStructuredOutput(t *testing.T) {
	req := chat.Request{
		SystemPrompt: "你是助手",
		Options:      chat.Options{Output: &chat.OutputFormat{Name: "city", Schema: json.RawMessage(`{"type":"object"}`)}},
		Messages:     []chat.Message{chat.NewUserTextMessage("你好")},
	}
	params, err := New(Config{Model: ModelGPT6Luna}).buildParams(req)
	if err != nil {
		t.Fatal(err)
	}
	if got := marshal(t, params); !strings.Contains(got, `"text":{"format":{"name":"city","schema":{"type":"object"},"strict":true,"type":"json_schema"}}`) {
		t.Fatalf("should use the native json_schema format: %s", got)
	}
	params, err = New(Config{Model: ModelGPT6Luna, NoStructuredOutput: true}).buildParams(req)
	if err != nil {
		t.Fatal(err)
	}
	if got := marshal(t, params); strings.Contains(got, "json_schema") || !strings.Contains(got, `JSON Schema:\n\n{\"type\":\"object\"}`) {
		t.Fatalf("without support the schema should go into instructions: %s", got)
	}
}

func TestBuildParamsToolChoice(t *testing.T) {
	req := chat.Request{
		Messages: []chat.Message{chat.NewUserTextMessage("你好")},
		Tools:    []chat.ToolDef{{Name: "lookup", InputSchema: json.RawMessage(`{"type":"object"}`)}},
	}
	for choice, want := range map[chat.ToolChoice]string{
		{Mode: chat.ToolChoiceRequired}: `"tool_choice":"required"`,
		{Mode: chat.ToolChoiceNone}:     `"tool_choice":"none"`,
		chat.ForceTool("lookup"):        `"tool_choice":{"name":"lookup","type":"function"}`,
	} {
		req.ToolChoice = choice
		params, err := New(Config{Model: ModelGPT6Luna}).buildParams(req)
		if err != nil {
			t.Fatal(err)
		}
		if got := marshal(t, params); !strings.Contains(got, want) {
			t.Fatalf("missing %s: %s", want, got)
		}
	}
	req.Tools = nil
	params, _ := New(Config{Model: ModelGPT6Luna}).buildParams(req)
	if got := marshal(t, params); strings.Contains(got, "tool_choice") {
		t.Fatalf("ToolChoice should be ignored without tools: %s", got)
	}
}

func TestConvertMediaKinds(t *testing.T) {
	client := New(Config{Model: ModelGPT6Luna})
	params, err := client.buildParams(chat.Request{Messages: []chat.Message{
		{Role: chat.RoleUser, Content: []chat.ContentBlock{
			chat.MediaURL("https://example.com/a.webp"),
			chat.Media([]byte("%PDF-1.7 正文")).WithName("合同.pdf"),
			chat.MediaURL("https://example.com/b.pdf"),
			chat.Media([]byte("a,b")).WithName("数据.csv"),
		}},
		{Role: chat.RoleAssistant, Provider: "other", Content: []chat.ContentBlock{{Type: chat.ContentTypeToolCall, ToolCall: &chat.ToolCall{ID: "c1", Name: "export"}}}},
		{Role: chat.RoleTool, ToolCallID: "c1", Content: []chat.ContentBlock{chat.Text("已导出"), chat.Media([]byte("%PDF-1.7 报表")).WithName("报表.pdf")}},
	}})
	if err != nil {
		t.Fatal(err)
	}
	got := marshal(t, params.Input)
	for _, want := range []string{
		`"image_url":"https://example.com/a.webp"`,
		`"file_data":"data:application/pdf;base64,`, `"filename":"合同.pdf"`,
		`"file_url":"https://example.com/b.pdf"`,
		`"filename":"数据.csv","type":"input_file"`, `"file_data":"data:text/csv;base64,`,
		`"filename":"报表.pdf"`,
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("missing %s:\n%s", want, got)
		}
	}
}
