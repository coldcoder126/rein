func TestTextSignatureRoundTrip(t *testing.T) {
	sig := encodeTextSignature("msg_1", "final_answer")
	got := decodeTextSignature(sig)
	if got.ID != "msg_1" || got.Phase != "final_answer" {
		t.Fatalf("wrong text signature round trip: %+v", got)
	}
	if decodeTextSignature("not json").ID != "" || decodeTextSignature(`{"v":2,"id":"x"}`).ID != "" {
		t.Fatal("invalid or unknown signature versions should be ignored")
	}
	if decodeTextSignature(`{"v":1,"id":"x","phase":"weird"}`).Phase != "" {
		t.Fatal("an unknown phase should be dropped")
	}
}

func TestGeneratedImageIsReplayedAfterToolResultsAsUserImage(t *testing.T) {
	image := chat.ContentBlock{Type: chat.ContentTypeMedia, MIMEType: "image/png", Data: []byte("img")}
	client := New(Config{Model: "m1"})
	params, err := client.buildParams(chat.Request{Messages: []chat.Message{
		chat.NewUserTextMessage("画一张"),
		{Role: chat.RoleAssistant, Provider: "openai", API: API, Model: "m1", StopReason: chat.StopReasonToolUse,
			Content: []chat.ContentBlock{image, toolCallBlock("c1", "lookup", `{}`, "")}},
		{Role: chat.RoleTool, ToolCallID: "c1", Content: []chat.ContentBlock{chat.Text("结果")}},
		chat.NewUserTextMessage("再画一张"),
	}})
	if err != nil {
		t.Fatal(err)
	}
	got := marshal(t, params.Input)
	out, img, next := strings.Index(got, `"type":"function_call_output"`), strings.Index(got, "Image generated by the assistant"), strings.Index(got, "再画一张")
	if !(out >= 0 && out < img && img < next) {
		t.Fatalf("generated images should come after the tool results and before the next user message (never between a function_call and its result): %s", got)
	}
}

