func marshal(t *testing.T, v any) string {
	t.Helper()
	raw, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

func toolCallBlock(id, name, args, sig string) chat.ContentBlock {
	return chat.ContentBlock{
		Type: chat.ContentTypeToolCall, Signature: sig,
		ToolCall: &chat.ToolCall{ID: id, Name: name, Arguments: json.RawMessage(args)},
	}
}

func TestBuildParamsBasics(t *testing.T) {
	client := New(Config{Model: ModelGPT6Luna})
	params, err := client.buildParams(chat.Request{
		SystemPrompt: "系统提示",
		Options:      chat.Options{Temperature: chat.Float(0), MaxTokens: 4},
		Messages:     []chat.Message{chat.NewUserTextMessage("你好")},
		Tools: []chat.ToolDef{{
			Name: "search", Description: "搜索",
			InputSchema: json.RawMessage(`{"type":"object","properties":{"q":{"type":"string"}},"required":["q"],"additionalProperties":false}`),
		}},
	})
	if err != nil {
		t.Fatal(err)
	}
	got := marshal(t, params)
	for _, want := range []string{
		`"model":"gpt-6-luna"`, `"instructions":"系统提示"`, `"store":false`, `"temperature":0`,
		`"max_output_tokens":16`, `"type":"function"`, `"name":"search"`, `"additionalProperties":false`,
		`"role":"user"`, `"type":"input_text"`,
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("request missing %s: %s", want, got)
		}
	}
	for _, unwanted := range []string{`"include"`, `"reasoning"`, `image_generation`} {
		if strings.Contains(got, unwanted) {
			t.Fatalf("the default config should not send %s: %s", unwanted, got)
		}
	}
}

func TestBuildParamsReasoningImageGenerationAndDisabledStoreParams(t *testing.T) {
	req := chat.Request{Messages: []chat.Message{chat.NewUserTextMessage("你好")}}

	got := marshal(t, mustParams(t, New(Config{Model: ModelGPT6Luna, Reasoning: true, ImageGeneration: true}), req))
	for _, want := range []string{`"include":["reasoning.encrypted_content"]`, `"reasoning":{"summary":"auto"}`, `"type":"image_generation"`, `"store":false`} {
		if !strings.Contains(got, want) {
			t.Fatalf("missing %s: %s", want, got)
		}
	}

	got = marshal(t, mustParams(t, New(Config{Model: ModelGPT6Luna, Reasoning: true, DisableStoreParams: true}), req))
	if strings.Contains(got, `"store"`) || strings.Contains(got, `"include"`) {
		t.Fatalf("DisableStoreParams should not send store/include: %s", got)
	}

	info := New(Config{Model: ModelGPT6Luna, ImageGeneration: true}).Info()
	if !info.ImageOutput || !info.SupportsMedia {
		t.Fatalf("Info should reflect image capabilities: %+v", info)
	}
}

func mustParams(t *testing.T, c *Client, req chat.Request) any {
	t.Helper()
	params, err := c.buildParams(req)
	if err != nil {
		t.Fatal(err)
	}
	return params
}

func TestReplayAssistantKeepsBlockOrderAndSignatures(t *testing.T) {
	const reasoningItem = `{"id":"rs_1","type":"reasoning","summary":[{"type":"summary_text","text":"先想"}],"encrypted_content":"ENC"}`
	client := New(Config{Model: "m1", ImageGeneration: true})
	params, err := client.buildParams(chat.Request{Messages: []chat.Message{
		chat.NewUserTextMessage("查"),
		{
			Role: chat.RoleAssistant, Provider: "openai", API: API, Model: "m1", StopReason: chat.StopReasonToolUse,
			Content: []chat.ContentBlock{
				{Type: chat.ContentTypeThinking, Text: "先想", Signature: reasoningItem},
				{Type: chat.ContentTypeText, Text: "我来查", Signature: `{"v":1,"id":"msg_abc","phase":"commentary"}`},
				toolCallBlock("call_1", "lookup", `{"q":"a"}`, "fc_1"),
				{Type: chat.ContentTypeMedia, MIMEType: "image/png", Data: []byte("img")},
			},
		},
		{Role: chat.RoleTool, ToolCallID: "call_1", Content: []chat.ContentBlock{chat.Text("结果")}},
	}})
	if err != nil {
		t.Fatal(err)
	}
	got := marshal(t, params.Input)
	if strings.Contains(got, "image_generation_call") {
		t.Fatalf("generated images should not be replayed as image_generation_call (statelessly it returns 404): %s", got)
	}

	order := []string{`"id":"rs_1"`, `"id":"msg_abc"`, `"id":"fc_1"`, `"type":"function_call_output"`, `Image generated by the assistant`, `"type":"input_image"`}
	last := -1
	for _, want := range order {
		idx := strings.Index(got, want)
		if idx <= last {
			t.Fatalf("wrong input item order, %s at %d is not after %d: %s", want, idx, last, got)
		}
		last = idx
	}
	for _, want := range []string{`"encrypted_content":"ENC"`, `"phase":"commentary"`, `"call_id":"call_1"`, `"arguments":"{\"q\":\"a\"}"`, `"image_url":"data:image/png;base64,aW1n"`, `"output":"结果"`} {
		if !strings.Contains(got, want) {
			t.Fatalf("missing %s: %s", want, got)
		}
	}
}

func TestReplayCrossModelDropsPrivateSignatures(t *testing.T) {
	client := New(Config{Model: "m1", ImageGeneration: true})
	params, err := client.buildParams(chat.Request{Messages: []chat.Message{
		chat.NewUserTextMessage("查"),
		{
			Role: chat.RoleAssistant, Provider: "openai", API: API, Model: "other-model", StopReason: chat.StopReasonToolUse,
			Content: []chat.ContentBlock{
				{Type: chat.ContentTypeThinking, Text: "旧模型的推理", Signature: `{"id":"rs_old","type":"reasoning"}`},
				{Type: chat.ContentTypeText, Text: "我来查", Signature: `{"v":1,"id":"msg_old"}`},
				toolCallBlock("call_1", "lookup", `{}`, "fc_old"),
			},
		},
		{Role: chat.RoleTool, ToolCallID: "call_1", Content: []chat.ContentBlock{chat.Text("结果")}},
	}})
	if err != nil {
		t.Fatal(err)
	}
	got := marshal(t, params.Input)
	for _, unwanted := range []string{"rs_old", "msg_old", "fc_old"} {
		if strings.Contains(got, unwanted) {
			t.Fatalf("replay across models should not carry the original model's item id %s: %s", unwanted, got)
		}
	}
	if !strings.Contains(got, "旧模型的推理") || !strings.Contains(got, `"call_id":"call_1"`) {
		t.Fatalf("replay across models should keep the content (thinking as text) and the calls: %s", got)
	}
}

func TestToolOutputWithImagesUsesContentArray(t *testing.T) {
	client := New(Config{Model: ModelGPT6Luna})
	image := chat.ContentBlock{Type: chat.ContentTypeMedia, MIMEType: "image/png", Data: []byte("img")}
	params, err := client.buildParams(chat.Request{Messages: []chat.Message{
		chat.NewUserTextMessage("看"),
		{Role: chat.RoleAssistant, Provider: "openai", API: API, Model: "gpt-6-luna", StopReason: chat.StopReasonToolUse,
			Content: []chat.ContentBlock{toolCallBlock("c1", "shot", `{}`, ""), toolCallBlock("c2", "shot", `{}`, "")}},
		{Role: chat.RoleTool, ToolCallID: "c1", Content: []chat.ContentBlock{chat.Text("截图"), image}},
		{Role: chat.RoleTool, ToolCallID: "c2", Content: []chat.ContentBlock{}},
	}})
	if err != nil {
		t.Fatal(err)
	}
	got := marshal(t, params.Input)
	if !strings.Contains(got, `"output":[{"text":"截图","type":"input_text"},{"detail":"auto","image_url":"data:image/png;base64,aW1n","type":"input_image"}]`) &&
		!strings.Contains(got, `"type":"input_image"`) {
		t.Fatalf("a tool result with an image should use a content array: %s", got)
	}
	if !strings.Contains(got, `"output":"(no tool output)"`) {
		t.Fatalf("an empty tool result should get placeholder text: %s", got)
	}
}

